#!/usr/bin/env python3
"""Turn the inlined 2K texture module into files the APK can ship separately.

`unity_preview/blacksmith-textures.js` carries the approved lossless 2048px PBR
maps as base64 data URIs. Base64 costs 33% more bytes than the WebP payload and
inflates `index.html` by ~23 MB, so the Android build stores the same bytes as
plain `hq2k/*.webp` files (served from the APK by the WebView shell) and keeps
only the two tiny FX sprites inline.

    python Tools/prepare_apk_textures.py --output build/apk-textures
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "unity_preview/blacksmith-textures.js"
FAMILIES = ("stone", "wood", "metal", "roof", "cobble")
KINDS = ("albedo", "normal", "orm")

FX_MODULE = """// Generated by Tools/prepare_apk_textures.py from blacksmith-textures.js.
// The two FX sprites are tiny, so they stay inline; the PBR maps are separate
// files (hq2k/*.webp in the APK, pack/*.webp once the HQ pack is installed).
export const BLACKSMITH_FX = {{
  smoke: '{smoke}',
  spark: '{spark}'
}};
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    text = args.source.read_text(encoding="utf-8")
    block = re.search(r"BLACKSMITH_PBR\s*=\s*(\{.*?\});", text, re.S)
    if not block:
        raise SystemExit("BLACKSMITH_PBR not found in the texture module")
    pairs = re.findall(r'"(\w+)":\{"albedo":"([^"]+)","normal":"([^"]+)","orm":"([^"]+)"\}',
                       block.group(1))
    found = {name for name, *_ in pairs}
    if found != set(FAMILIES) or len(pairs) != len(FAMILIES):
        raise SystemExit(f"unexpected families: {sorted(found)}")

    out = args.output
    maps_dir = out / "hq2k"
    maps_dir.mkdir(parents=True, exist_ok=True)

    records = []
    for family, *uris in pairs:
        for kind, uri in zip(KINDS, uris):
            if not uri.startswith("data:image/webp;base64,"):
                raise SystemExit(f"{family}/{kind} is not an inline WebP")
            raw = base64.b64decode(uri.split(",", 1)[1])
            with Image.open(io.BytesIO(raw)) as image:
                if image.size != (2048, 2048) or image.format != "WEBP":
                    raise SystemExit(f"{family}/{kind}: unexpected {image.format} {image.size}")
            name = f"{family}_{kind}.webp"
            (maps_dir / name).write_bytes(raw)
            records.append({"path": f"hq2k/{name}", "family": family, "kind": kind,
                            "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(),
                            "resolution": [2048, 2048]})

    fx = dict(re.findall(r'"(smoke|spark)":"(data:image/png;base64,[^"]+)"', text))
    if set(fx) != {"smoke", "spark"}:
        raise SystemExit("FX sprites missing from the texture module")
    (out / "blacksmith-fx.js").write_text(
        FX_MODULE.format(smoke=fx["smoke"], spark=fx["spark"]), encoding="utf-8")

    manifest = {
        "generator": "Tools/prepare_apk_textures.py",
        "source": str(args.source.relative_to(ROOT)),
        "encoding": "lossless WebP (VP8L), 2048x2048",
        "mapCount": len(records),
        "totalBytes": sum(record["bytes"] for record in records),
        "maps": records,
    }
    (maps_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({k: manifest[k] for k in ("mapCount", "totalBytes")}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
